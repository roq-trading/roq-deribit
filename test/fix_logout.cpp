#include <gtest/gtest.h>

#include "roq/core/fix/reader.h"

#include "roq/deribit/fix/logout.h"

using namespace roq;  // NOLINT
using namespace roq::deribit;  // NOLINT

TEST(fix_logout, parse_message) {
  const char message[] = {
    0x38, 0x3d, 0x46, 0x49, 0x58, 0x2e, 0x34, 0x2e,
    0x34, 0x01, 0x39, 0x3d, 0x39, 0x31, 0x01, 0x33,
    0x35, 0x3d, 0x35, 0x01, 0x34, 0x39, 0x3d, 0x52,
    0x4f, 0x51, 0x5f, 0x54, 0x52, 0x41, 0x44, 0x49,
    0x4e, 0x47, 0x01, 0x35, 0x36, 0x3d, 0x44, 0x45,
    0x52, 0x49, 0x42, 0x49, 0x54, 0x5f, 0x53, 0x45,
    0x52, 0x56, 0x45, 0x52, 0x01, 0x33, 0x34, 0x3d,
    0x31, 0x01, 0x35, 0x32, 0x3d, 0x32, 0x30, 0x31,
    0x39, 0x30, 0x39, 0x30, 0x31, 0x2d, 0x31, 0x37,
    0x3a, 0x35, 0x37, 0x3a, 0x33, 0x36, 0x2e, 0x31,
    0x33, 0x30, 0x01, 0x35, 0x38, 0x3d, 0x69, 0x6e,
    0x76, 0x61, 0x6c, 0x69, 0x64, 0x5f, 0x63, 0x72,
    0x65, 0x64, 0x65, 0x6e, 0x74, 0x69, 0x61, 0x6c,
    0x73, 0x01, 0x31, 0x30, 0x3d, 0x32, 0x34, 0x34,
    0x01};
  int results = 0;
  auto bytes = core::fix::Reader::dispatch(
      [&](const core::fix::message_t& message) {
        ++results;
        EXPECT_EQ(message.header.msg_type, core::fix::MsgType::LOGOUT);
        auto result = fix::Logout::parse(message);
        EXPECT_EQ(result.text, "invalid_credentials");
      },
      message,
      std::size(message));
  EXPECT_EQ(bytes, std::size(message));
  EXPECT_EQ(results, 1);
}
